function getProfiles() {
    let profiles = JSON.parse(JSON.stringify(DEFAULT_PROFILES));
    const saved = localStorage.getItem('hostelhoard_profiles_data');
    if (saved) {
        try {
            const parsed = JSON.parse(saved);
            // Auto-migrate if stored data contains old placeholder names or mismatched images
            const hasLegacyOrders = parsed?.user1?.orders?.some((o) =>
                o.name?.includes('Product 1') ||
                (o.name === 'Lamp' && o.img?.includes('portable-fan')) ||
                (o.img === 'images/portable-fan.webp' && !o.name?.toLowerCase().includes('fan'))
            );
            if (hasLegacyOrders) {
                parsed.user1.orders = JSON.parse(JSON.stringify(DEFAULT_PROFILES.user1.orders));
                parsed.user2.orders = JSON.parse(JSON.stringify(DEFAULT_PROFILES.user2.orders));
                localStorage.setItem('hostelhoard_profiles_data', JSON.stringify(parsed));
            }
            profiles = parsed;
        } catch (e) {}
    }

    
    const auth = localStorage.getItem('hostelhoard_auth_user');
    if (auth) {
        try {
            const authUser = JSON.parse(auth);
            if (authUser && authUser.name) {
                profiles.user1.name = authUser.name;
                if (authUser.email) profiles.user1.email = authUser.email;
                if (authUser.room) profiles.user1.room = authUser.room;
            }
        } catch (e) {}
    }
    return profiles;
}

