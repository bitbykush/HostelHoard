document.addEventListener('click', (e) => {
    
    const switchBtn = e.target.closest('.switch-btn');
    if (switchBtn) {
        e.preventDefault();
        e.stopPropagation();
        const targetUser =
            switchBtn.getAttribute('data-user') || (getActiveProfileId() === 'user1' ? 'user2' : 'user1');
        setActiveProfileId(targetUser);
        const profiles = getProfiles();
        const targetProfile = profiles[targetUser];
        renderProfilePage();
        showToast(`Switched profile to ${targetProfile.name}! 👋`);
        return;
    }

    
    const editBtn = e.target.closest('.edit-profile-btn');
    if (editBtn) {
        e.preventDefault();
        e.stopPropagation();
        const userId = editBtn.getAttribute('data-user') || getActiveProfileId();
        const profiles = getProfiles();
        const currentName = profiles[userId]?.name || 'John Doe';
        const newName = prompt('Enter new display name for this profile:', currentName);
        if (newName && newName.trim()) {
            profiles[userId].name = newName.trim();
            saveProfiles(profiles);
            if (userId === 'user1') {
                const auth = localStorage.getItem('hostelhoard_auth_user');
                if (auth) {
                    try {
                        const authUser = JSON.parse(auth);
                        authUser.name = newName.trim();
                        localStorage.setItem('hostelhoard_auth_user', JSON.stringify(authUser));
                    } catch (e) {}
                }
            }
            renderProfilePage();
            showToast(`Profile name updated to ${newName.trim()}!`);
        }
        return;
    }

    
    const addAddressBtn = e.target.closest('#add-address-btn');
    if (addAddressBtn) {
        e.preventDefault();
        e.stopPropagation();
        const profiles = getProfiles();
        const activeId = getActiveProfileId();
        const activeProfile = profiles[activeId] || profiles.user1;
        if (!activeProfile.addresses) activeProfile.addresses = [];

        const newAddr = prompt('Enter new delivery address (e.g., Room 305, Block C, Campus):', '');
        if (newAddr && newAddr.trim()) {
            activeProfile.addresses.push(newAddr.trim());
            saveProfiles(profiles);
            renderProfilePage();
            showToast('New address saved! 📍');
        }
        return;
    }

    
    const editAddressBtn = e.target.closest('.edit-address-btn');
    if (editAddressBtn) {
        e.preventDefault();
        e.stopPropagation();
        const idx = parseInt(editAddressBtn.getAttribute('data-index'), 10);
        const profiles = getProfiles();
        const activeId = getActiveProfileId();
        const activeProfile = profiles[activeId] || profiles.user1;
        if (activeProfile.addresses && activeProfile.addresses[idx] !== undefined) {
            const currentAddr = activeProfile.addresses[idx];
            const updatedAddr = prompt('Edit delivery address:', currentAddr);
            if (updatedAddr && updatedAddr.trim()) {
                activeProfile.addresses[idx] = updatedAddr.trim();
                saveProfiles(profiles);
                renderProfilePage();
                showToast('Address updated successfully! 🏠');
            }
        }
        return;
    }

    
    const deleteAddressBtn = e.target.closest('.delete-address-btn');
    if (deleteAddressBtn) {
        e.preventDefault();
        e.stopPropagation();
        const idx = parseInt(deleteAddressBtn.getAttribute('data-index'), 10);
        const profiles = getProfiles();
        const activeId = getActiveProfileId();
        const activeProfile = profiles[activeId] || profiles.user1;
        if (activeProfile.addresses && activeProfile.addresses[idx] !== undefined) {
            activeProfile.addresses.splice(idx, 1);
            saveProfiles(profiles);
            renderProfilePage();
            showToast('Address removed.');
        }
        return;
    }

    
    const signOutBtn = e.target.closest('#sign-out-btn') || e.target.closest('.sign-out-btn');
    if (signOutBtn) {
        e.preventDefault();
        localStorage.removeItem('hostelhoard_auth_user');
        localStorage.setItem('hostelhoard_active_profile', 'user1');
        showToast('Signed out successfully! Redirecting...');
        setTimeout(() => {
            window.location.href = 'signin.html';
        }, 500);
        return;
    }
});

