function getCurrentLanguage() {
    return localStorage.getItem('hostelhoard_lang') || 'en';
}

function applyLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    const dict = TRANSLATIONS[lang];


    document.documentElement.lang = lang;
    if (lang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
    }


    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    document.querySelectorAll('select.language-selector, select#lang-select').forEach((sel) => {
        sel.value = lang;
    });


    document.querySelectorAll('.card').forEach((card) => {
        const prodName = card.querySelector('.product-name')?.textContent || '';
        const buttons = card.querySelectorAll('a.btn, button.btn');
        buttons.forEach((btn) => {
            const current = btn.textContent.trim().toLowerCase();
            if (
                current.includes('cart') ||
                current.includes('carrito') ||
                current.includes('panier') ||
                current.includes('warenkorb') ||
                current.includes('कार्ट') ||
                current.includes('购物车') ||
                current.includes('السلة') ||
                btn.classList.contains('add-to-cart-btn')
            ) {
                btn.textContent = dict.add_to_cart;
                btn.setAttribute('aria-label', `${dict.add_to_cart}: ${prodName}`);
            } else if (
                current.includes('buy') ||
                current.includes('comprar') ||
                current.includes('acheter') ||
                current.includes('kaufen') ||
                current.includes('खरीदें') ||
                current.includes('购买') ||
                current.includes('شراء') ||
                btn.classList.contains('buy-now-btn')
            ) {
                btn.textContent = dict.buy_now;
                btn.setAttribute('aria-label', `${dict.buy_now}: ${prodName}`);
            }
        });
    });

  
    updateCartUI();
    renderProfilePage();
}

window.changeLanguage = function (lang) {
    localStorage.setItem('hostelhoard_lang', lang);
    applyLanguage(lang);

    const langNames = {
        en: 'English',
        es: 'Español',
        fr: 'Français',
        de: 'Deutsch',
        hi: 'हिन्दी',
        zh: '中文',
        ar: 'العربية'
    };
    showToast(`🌐 Language set to ${langNames[lang] || lang.toUpperCase()}`);
};


function showToast(message) {
    let toast = document.getElementById('app-toast');
    if (!toast) {
        toast = document.createElement('div');
        toast.id = 'app-toast';
        toast.className = 'app-toast';
        toast.setAttribute('role', 'status');
        toast.setAttribute('aria-live', 'polite');
        toast.setAttribute('aria-atomic', 'true');
        document.body.appendChild(toast);
    }
    toast.textContent = message;
    toast.classList.add('active');
    if (window.toastTimeout) clearTimeout(window.toastTimeout);
    window.toastTimeout = setTimeout(() => {
        toast.classList.remove('active');
    }, 3000);
}
window.showToast = showToast;


