const currentProfile = document.getElementById('current-profile');
const otherProfileInfo = document.getElementById('other-profile-info');
const profileBtn = document.getElementById('profile-btn');
const profileGif = document.getElementById('profile-gif');

if (profileBtn && profileGif) {
    profileBtn.addEventListener('mouseenter', () => {
        profileGif.src = 'images/profile-infinite-loop.gif';
    });
    profileBtn.addEventListener('mouseleave', () => {
        profileGif.src = 'images/profile.gif';
    });
}

function toggleProfileDrawer(open) {
    if (!otherProfileInfo) return;
    const shouldOpen = open !== undefined ? open : !otherProfileInfo.classList.contains('other-profile-info-active');
    if (shouldOpen) {
        toggleCartDropdown(false);
        closeAllPanels();
        otherProfileInfo.classList.add('other-profile-info-active');
        currentProfile?.setAttribute('aria-expanded', 'true');
        const firstBtn = otherProfileInfo.querySelector('button, a');
        firstBtn?.focus();
    } else {
        otherProfileInfo.classList.remove('other-profile-info-active');
        currentProfile?.setAttribute('aria-expanded', 'false');
    }
}

if (currentProfile && otherProfileInfo) {
    currentProfile.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        toggleProfileDrawer();
    });
}

if (profileBtn && otherProfileInfo) {
    profileBtn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        toggleProfileDrawer();
    });
}

const barSpacer = document.querySelector('.bar-spacer');
if (barSpacer && otherProfileInfo) {
    barSpacer.addEventListener('click', () => {
        toggleProfileDrawer(false);
        currentProfile?.focus();
    });
}

document.addEventListener('click', (e) => {
    if (otherProfileInfo && otherProfileInfo.classList.contains('other-profile-info-active')) {
        if (
            !otherProfileInfo.contains(e.target) &&
            e.target !== currentProfile &&
            (!profileBtn || !profileBtn.contains(e.target))
        ) {
            toggleProfileDrawer(false);
        }
    }
});


document.addEventListener('keydown', (e) => {
    
    if (
        (e.key === 'Enter' || e.key === ' ') &&
        e.target.getAttribute('role') === 'button' &&
        e.target.tagName !== 'BUTTON' &&
        e.target.tagName !== 'INPUT'
    ) {
        e.preventDefault();
        e.target.click();
        return;
    }

    
    if (e.key === 'Escape') {
        if (cartDropdown && cartDropdown.classList.contains('active')) {
            toggleCartDropdown(false);
            cartBtn?.focus();
            return;
        }
        if (settingsPanel && settingsPanel.classList.contains('active')) {
            closeAllPanels();
            settingsBtn?.focus();
            return;
        }
        if (notifPanel && notifPanel.classList.contains('active')) {
            closeAllPanels();
            notifBtn?.focus();
            return;
        }
        if (otherProfileInfo && otherProfileInfo.classList.contains('other-profile-info-active')) {
            toggleProfileDrawer(false);
            currentProfile?.focus();
            return;
        }
        if (mobileMenu && mobileMenu.classList.contains('active')) {
            closeMobileMenu();
            burgerBtn?.focus();
            return;
        }
    }
});

const burgerBtn = document.getElementById('burger-btn');
const mobileMenu = document.getElementById('mobile-menu');
const menuBackdrop = document.getElementById('menu-backdrop');

function openMobileMenu() {
    if (!mobileMenu || !burgerBtn) return;
    toggleCartDropdown(false);
    closeAllPanels();
    mobileMenu.classList.add('active');
    burgerBtn.classList.add('active');
    burgerBtn.setAttribute('aria-expanded', 'true');
    burgerBtn.setAttribute('aria-label', 'Close navigation menu');
    mobileMenu.setAttribute('aria-hidden', 'false');
    if (menuBackdrop) {
        menuBackdrop.classList.add('active');
    }
}

function closeMobileMenu() {
    if (!mobileMenu || !burgerBtn) return;
    mobileMenu.classList.remove('active');
    burgerBtn.classList.remove('active');
    burgerBtn.setAttribute('aria-expanded', 'false');
    burgerBtn.setAttribute('aria-label', 'Toggle navigation menu');
    mobileMenu.setAttribute('aria-hidden', 'true');
    if (menuBackdrop) {
        menuBackdrop.classList.remove('active');
    }
}

function toggleMobileMenu() {
    if (!mobileMenu) return;
    const isOpen = mobileMenu.classList.contains('active');
    if (isOpen) {
        closeMobileMenu();
    } else {
        openMobileMenu();
    }
}

if (burgerBtn && mobileMenu) {
    burgerBtn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        toggleMobileMenu();
    });

    if (menuBackdrop) {
        menuBackdrop.addEventListener('click', () => {
            closeMobileMenu();
        });
    }

    document.addEventListener('click', (e) => {
        if (mobileMenu.classList.contains('active')) {
            if (!mobileMenu.contains(e.target) && !burgerBtn.contains(e.target)) {
                closeMobileMenu();
            }
        }
    });

    const mobileLinks = mobileMenu.querySelectorAll('a');
    mobileLinks.forEach((link) => {
        link.addEventListener('click', () => {
            closeMobileMenu();
        });
    });

    window.addEventListener('resize', () => {
        if (mobileMenu.classList.contains('active') && window.innerWidth > 1100) {
            closeMobileMenu();
        }
    });
}


document.addEventListener('DOMContentLoaded', () => {
    const savedLang = getCurrentLanguage();
    applyLanguage(savedLang);
    updateCartUI();
    renderProfilePage();
});
