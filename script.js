document.addEventListener('click', (e) => {
    const target = e.target;


    if (target.classList.contains('cart-qty-btn')) {
        e.preventDefault();
        e.stopPropagation();
        const id = target.getAttribute('data-id');
        if (target.classList.contains('plus')) {
            updateCartQuantity(id, 1);
        } else if (target.classList.contains('minus')) {
            updateCartQuantity(id, -1);
        }
        return;
    }

    
    if (target.classList.contains('cart-item-remove')) {
        e.preventDefault();
        e.stopPropagation();
        const id = target.getAttribute('data-id');
        removeFromCart(id);
        showToast('Item removed from cart.');
        return;
    }

    
    if (target.id === 'cart-clear-btn' || target.closest('#cart-clear-btn')) {
        e.preventDefault();
        e.stopPropagation();
        clearCart();
        showToast('Cart cleared.');
        return;
    }

    
    if (target.id === 'cart-checkout-btn' || target.closest('#cart-checkout-btn')) {
        e.preventDefault();
        e.stopPropagation();
        const cart = getCart();
        if (cart.length === 0) {
            showToast('Your cart is empty! Add items first.');
            return;
        }
        const total = cart.reduce((sum, item) => sum + item.price * item.quantity, 0);
        clearCart();
        toggleCartDropdown(false);
        cartBtn?.focus();
        showToast(`🎉 Order confirmed! Total: ₹${total.toFixed(2)}. Check your hostel room soon!`);
        return;
    }

    
    if (cartDropdown && cartDropdown.classList.contains('active')) {
        const cartWrapper = document.getElementById('cart-wrapper');
        if (cartWrapper && !cartWrapper.contains(target)) {
            toggleCartDropdown(false);
        }
    }
});


