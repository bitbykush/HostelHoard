const signupToggle = document.getElementById('signup-toggle');
const signinToggle = document.getElementById('signin-toggle');
const signinSection = document.getElementById('signin');
const signupSection = document.getElementById('signup');

function showSignInTab() {
    if (!signinSection || !signupSection) return;
    signinSection.style.display = 'flex';
    signupSection.style.display = 'none';
    if (signinToggle && signupToggle) {
        signinToggle.style.backgroundColor = 'var(--secondary-color)';
        signupToggle.style.backgroundColor = 'var(--success-color)';
        signinToggle.setAttribute('aria-selected', 'true');
        signupToggle.setAttribute('aria-selected', 'false');
    }
}

function showSignUpTab() {
    if (!signinSection || !signupSection) return;
    signupSection.style.display = 'flex';
    signinSection.style.display = 'none';
    if (signinToggle && signupToggle) {
        signupToggle.style.backgroundColor = 'var(--secondary-color)';
        signinToggle.style.backgroundColor = 'var(--success-color)';
        signupToggle.setAttribute('aria-selected', 'true');
        signinToggle.setAttribute('aria-selected', 'false');
    }
}

if (signupToggle && signinToggle && signupSection && signinSection) {
    signupToggle.addEventListener('click', (e) => {
        e.preventDefault();
        showSignUpTab();
    });

    signinToggle.addEventListener('click', (e) => {
        e.preventDefault();
        showSignInTab();
    });

    if (window.location.hash === '#signup') {
        showSignUpTab();
    } else {
        showSignInTab();
    }
}


function showAuthFeedback(elementId, message, isError = true) {
    const feedbackEl = document.getElementById(elementId);
    if (!feedbackEl) return;
    feedbackEl.textContent = message;
    feedbackEl.className = 'auth-feedback ' + (isError ? 'error' : 'success');
}

